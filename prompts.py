def build_project_section_prompt(topic, section_name, instruction, allow_list=False):
    if allow_list:
        list_rule = (
            "Напиши ответ ТОЛЬКО в виде нумерованного списка.\n"
            "Каждый пункт с новой строки.\n"
            "Пример:\n"
            "1. Первый пункт\n"
            "2. Второй пункт\n"
            "3. Третий пункт\n"
        )
    else:
        list_rule = (
            "Напиши ответ сплошным текстом.\n"
            "Не используй списки и нумерацию."
        )

    return (
        f"Тема проекта: {topic}\n\n"
        f"Напиши раздел проекта: {section_name}.\n"
        f"{instruction}\n\n"
        f"{list_rule}\n\n"
        "Требования к тексту:\n"
        "Без заголовков.\n"
        "Без эмодзи.\n"
        "Простой учебный стиль.\n"
        "Без разговорных фраз.\n"
    )


